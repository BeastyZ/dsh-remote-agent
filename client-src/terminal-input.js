// xterm 5.5's public onData mixes user input with answers synthesized by its
// VT parser. Its CoreService.onUserInput is the only per-event discriminator,
// already used by the canvas addon's internal renderer contract. Keep this
// small boundary next to the pinned xterm version, rather than guessing from
// escape sequences (which would break mouse and focus protocols).
export function createTerminalInput(term, forward) {
  let replaying = true
  let pendingUserInput = 0
  let queuedInput = []
  const userInput = term._core.coreService.onUserInput(() => { pendingUserInput++ })
  const data = term.onData((chunk) => {
    if (pendingUserInput > 0) {
      pendingUserInput--
      if (replaying) queuedInput.push(chunk)
      else forward(chunk)
    } else if (!replaying) {
      forward(chunk)
    }
    // Protocol answers generated by replay are intentionally discarded.
  })
  const binary = term.onBinary(forward)
  return {
    finishReplay() {
      replaying = false
      const queue = queuedInput
      queuedInput = []
      for (const chunk of queue) forward(chunk)
    },
    dispose() {
      userInput.dispose()
      data.dispose()
      binary.dispose()
      queuedInput = []
    },
  }
}
