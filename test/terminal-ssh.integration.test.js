// Opt-in real SSH test: DSH_TEST_SSH_ALIAS=<configured-alias> node --test ...
// Creates one uniquely named plugin-owned tmux session and deletes only that
// session. No existing remote or local user session is touched.
import test from 'node:test'
import assert from 'node:assert/strict'
import { spawn, execFile } from 'node:child_process'
import { promisify } from 'node:util'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { TerminalHub } from '../host/terminal.js'

const execute = promisify(execFile)
const alias = process.env.DSH_TEST_SSH_ALIAS

test('real SSH tmux process survives Host detach and is reattached with the same pane PID', { skip: !alias, timeout: 45000 }, async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'dsh-agent-ssh-test-'))
  const host = { id: 'integration-test-host' }
  const pool = {
    ensure: async () => ({ ok: true }), resolveHost: () => host,
    ptyArgv: async (_host, command) => ['/usr/bin/ssh', '-tt', '-o', 'BatchMode=yes', '-o', 'ConnectTimeout=8', alias, command],
    ptyEnv: () => ({ ...process.env, TERM: 'xterm-256color' }),
    exec: async (_host, command) => {
      try {
        const { stdout, stderr } = await execute('/usr/bin/ssh', ['-o', 'BatchMode=yes', '-o', 'ConnectTimeout=8', alias, command], { timeout: 15000, maxBuffer: 1024 * 1024 })
        return { ok: true, stdout, stderr }
      } catch (error) {
        return { ok: false, code: 'SSH', message: error.message, stdout: error.stdout || '', stderr: error.stderr || '', exitCode: error.code }
      }
    },
  }
  const diagnostics = [];
  const ctx = { subprocess: { spawnTerminal: async spec => {
    const child = spawn(spec.argv[0], spec.argv.slice(1), { env: spec.env, stdio: ['pipe', 'pipe', 'pipe'] })
    const done = new Promise((resolve, reject) => {
      child.once('error', reject)
      child.once('close', code => resolve({ exitCode: code }))
    })
    child.stderr.on('data', chunk => diagnostics.push(chunk.toString()));
    return {
      output: child.stdout, done,
      write: async data => { child.stdin.write(data) },
      resize: async () => {},
      terminate: async () => { child.kill('SIGTERM'); await done },
    }
  } } }
  const a = new TerminalHub(ctx, pool, { archiveDir: dir })
  let b
  let id
  try {
    const result = await a.create({ host, cwd: '/tmp', title: 'DSH persistence integration test', command: 'printf "DSH_PERSISTENCE_PROBE\\n"; exec bash --noprofile --norc -i' })
    assert(result.ok, result.message)
    assert(result.session.persistent, 'tmux is available on test host')
    id = result.session.id
    let offset = 0
    let output = ''
    for (let i = 0; i < 8 && !output.includes('DSH_PERSISTENCE_PROBE'); i++) {
      const read = await a.read(id, offset, 3000)
      output += read.data
      offset = read.nextOffset
    }
    assert(output.includes('DSH_PERSISTENCE_PROBE'), `remote output: ${JSON.stringify(output.slice(-2000))}; stderr: ${diagnostics.join('').slice(-2000)}`)
    const target = a.get(id).remoteName
    const before = await pool.exec(host, `tmux -L dsh-remote-agent display-message -p -t '${target}' '#{pane_pid}'`)
    assert(before.ok)
    await a.dispose()
    b = new TerminalHub(ctx, pool, { archiveDir: dir })
    assert.equal(b.list()[0].id, id)
    const saved = await b.read(id, 0, 0)
    assert(saved.data.includes('DSH_PERSISTENCE_PROBE'), `saved view: ${JSON.stringify(saved.data.slice(-1000))}; raw tail: ${JSON.stringify(b.get(id).buffer.slice(-1600))}`)
    const resumed = await b.resume(id, host)
    assert(resumed.ok, resumed.message)
    const after = await pool.exec(host, `tmux -L dsh-remote-agent display-message -p -t '${target}' '#{pane_pid}'`)
    assert(after.ok)
    assert.equal(after.stdout.trim(), before.stdout.trim(), 'same remote process after reconnect')
    assert((await b.close(id)).ok)
    assert.equal(new TerminalHub(ctx, pool, { archiveDir: dir }).list().length, 0)
  } finally {
    // The id is generated by this fixture and belongs only to this test.
    if (id) {
      const cleanup = b || a
      if (cleanup.get(id)) await cleanup.close(id)
    }
    await a.dispose()
    if (b) await b.dispose()
    const resolved = path.resolve(dir)
    assert.equal(path.dirname(resolved), path.resolve(os.tmpdir()))
    assert(path.basename(resolved).startsWith('dsh-agent-ssh-test-'))
    fs.rmSync(resolved, { recursive: true, force: true })
  }
})
